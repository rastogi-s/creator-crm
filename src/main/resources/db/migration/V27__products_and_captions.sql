-- Her shop links: Amazon, Walmart and other products she recommends, each with its affiliate link, tags and an
-- optional discount code. The caption maker puts these exact links into descriptions, DMs and her bio list.
CREATE TABLE products (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(200)  NOT NULL,
    store         VARCHAR(20)   NOT NULL,   -- AMAZON | WALMART | OTHER
    url           VARCHAR(2000) NOT NULL,
    item_id       VARCHAR(40),              -- Amazon ASIN or Walmart item number
    brand         VARCHAR(200),
    tags          VARCHAR(300),             -- comma-separated, lower case
    code          VARCHAR(100),             -- discount code, e.g. AVA20
    times_used    INTEGER       NOT NULL DEFAULT 0,
    last_used_at  TIMESTAMP WITH TIME ZONE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Captions for one post on YouTube, Instagram and TikTok: what the video is about, the products in it, and what
-- Claude wrote. The links are added by the app from the products table when the captions are shown.
CREATE TABLE caption_sets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200),
    about           VARCHAR(4000) NOT NULL,
    note            VARCHAR(1000),
    opportunity_id  BIGINT,
    product_ids     VARCHAR(1000),          -- comma-separated, in the order shown
    youtube_format  VARCHAR(10)   NOT NULL, -- SHORT | VIDEO
    platforms       VARCHAR(50)   NOT NULL, -- comma-separated: YOUTUBE,INSTAGRAM,TIKTOK
    picture_count   INTEGER       NOT NULL DEFAULT 0,
    status          VARCHAR(20)   NOT NULL, -- READY | FAILED
    draft_json      VARCHAR,
    error           VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_caption_sets_created ON caption_sets(created_at);
