-- Content ideas for a deal: the brand's guidelines (read from the brief email and its PDF, Word or PowerPoint files,
-- or pasted by the creator) and the reel and video ideas Claude wrote from them and her profile. Each run is a row;
-- the deal shows the newest. The files themselves aren't kept; Gmail still has them.
CREATE TABLE content_ideas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id   BIGINT        NOT NULL REFERENCES opportunities(id),
    message_id       BIGINT,
    source           VARCHAR(20)   NOT NULL,   -- EMAIL | PASTED | DEAL
    status           VARCHAR(20)   NOT NULL,   -- READY | FAILED
    guidelines       VARCHAR,
    file_names       VARCHAR(1000),
    note             VARCHAR(1000),
    ideas_json       VARCHAR,
    error            VARCHAR(500),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_content_ideas_opportunity ON content_ideas(opportunity_id);
