-- Campaign wrap-up: the post a deal produced, its numbers, and the results recap email that carries them as a PDF.
CREATE TABLE campaign_results (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opportunity_id  BIGINT NOT NULL REFERENCES opportunities (id),
    post_url        VARCHAR(500),
    media_id        VARCHAR(100),
    media_type      VARCHAR(40),
    caption         VARCHAR(1000),
    posted_at       TIMESTAMP WITH TIME ZONE,
    source          VARCHAR(20) NOT NULL,   -- INSTAGRAM (numbers fetched) | MANUAL (typed in)
    reach           BIGINT,
    views           BIGINT,
    likes           BIGINT,
    comments        BIGINT,
    saves           BIGINT,
    shares          BIGINT,
    fetched_at      TIMESTAMP WITH TIME ZONE,
    error           VARCHAR(500),
    recap_drafted_at TIMESTAMP WITH TIME ZONE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE UNIQUE INDEX idx_campaign_results_opportunity ON campaign_results (opportunity_id);

ALTER TABLE drafts ADD COLUMN result_id BIGINT;
