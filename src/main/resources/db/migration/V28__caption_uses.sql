-- What she actually copied from Post captions, one row per caption field, next to what Claude wrote. New captions
-- learn from these: her edits most of all.
CREATE TABLE caption_uses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caption_set_id  BIGINT        NOT NULL REFERENCES caption_sets (id) ON DELETE CASCADE,
    field           VARCHAR(30)   NOT NULL, -- YOUTUBE_TITLE | YOUTUBE_DESCRIPTION | YOUTUBE_PINNED | INSTAGRAM_CAPTION | INSTAGRAM_STORY | TIKTOK_CAPTION | DM_REPLY
    written_text    VARCHAR(6000),          -- what the app showed her (Claude's text plus her links)
    used_text       VARCHAR(6000) NOT NULL, -- what she copied
    edited          BOOLEAN       NOT NULL DEFAULT FALSE,
    used_at         TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_caption_uses_used ON caption_uses(used_at);
CREATE UNIQUE INDEX idx_caption_uses_field ON caption_uses(caption_set_id, field);
