-- Brand news: launches, teasers and restocks from brands she has worked with, collected from free sources (her
-- inbox, the brand's Instagram posts and website feeds, a public news index) and used as the "why now" of re-pitches.
CREATE TABLE brand_news (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand_id        BIGINT NOT NULL REFERENCES brands (id),
    source          VARCHAR(20)   NOT NULL,     -- EMAIL | INSTAGRAM | WEBSITE | NEWS | WEB_SEARCH
    item_key        VARCHAR(600)  NOT NULL,     -- the same item found again is not stored twice
    title           VARCHAR(500)  NOT NULL,
    snippet         VARCHAR(2000),
    url             VARCHAR(2000),
    message_id      BIGINT,                     -- source EMAIL: the newsletter in her inbox
    published_at    TIMESTAMP WITH TIME ZONE,
    found_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Filled in by Claude's sort; null = not sorted yet
    kind            VARCHAR(20),                -- LAUNCH | TEASER | RESTOCK | NEW_RANGE | CAMPAIGN | OTHER
    headline        VARCHAR(300),
    pitch_idea      VARCHAR(500),
    fit             INT,
    hidden          BOOLEAN NOT NULL DEFAULT FALSE,
    used_in_draft_id BIGINT,
    CONSTRAINT uq_brand_news_item UNIQUE (brand_id, item_key)
);
CREATE INDEX ix_brand_news_brand ON brand_news (brand_id);
CREATE INDEX ix_brand_news_draft ON brand_news (used_in_draft_id);

